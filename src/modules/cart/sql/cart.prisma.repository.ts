import { Prisma } from '@prisma-client';
import type { Cart as CartRow, CartItem as CartItemRow } from '@prisma-client';

import type { SqlClient } from '@core/database/sql/prisma.adapter';
import type { CartRepository, NewCart, NewCartItem } from '../cart.repository';
import type { Cart, CartItem, CartWithItems } from '../cart.types';

const RECORD_NOT_FOUND = 'P2025';

const ITEMS = { orderBy: { createdAt: 'asc' } } as const;

function toCart(row: CartRow): Cart {
  return {
    id: row.id,
    customerId: row.customerId,
    currency: row.currency,
    createdAt: row.createdAt,
    updatedAt: row.updatedAt,
  };
}

function toItem(row: CartItemRow): CartItem {
  return {
    id: row.id,
    cartId: row.cartId,
    variantId: row.variantId,
    quantity: row.quantity,
    unitPriceCents: row.unitPriceCents,
    createdAt: row.createdAt,
    updatedAt: row.updatedAt,
  };
}

function errorCodeOf(error: unknown): string | undefined {
  return error instanceof Prisma.PrismaClientKnownRequestError ? error.code : undefined;
}

export class PrismaCartRepository implements CartRepository {
  constructor(private readonly client: SqlClient) {}

  async findOrCreate(cart: NewCart): Promise<Cart> {
    // Upsert rather than read-then-create: two tabs adding their first item at the same moment
    // would both find nothing and both insert, and the unique index would fail one of them.
    // The id it would use is generated by the service, so a cart that already exists simply
    // ignores it — identity stays domain-owned either way.
    const row = await this.client.cart.upsert({
      where: { customerId: cart.customerId },
      create: cart,
      update: {},
    });

    return toCart(row);
  }

  async findWithItems(customerId: string): Promise<CartWithItems | null> {
    const row = await this.client.cart.findUnique({
      where: { customerId },
      include: { items: ITEMS },
    });

    return row === null ? null : { ...toCart(row), items: row.items.map(toItem) };
  }

  async upsertItem(item: NewCartItem): Promise<void> {
    await this.client.cartItem.upsert({
      where: { cartId_variantId: { cartId: item.cartId, variantId: item.variantId } },
      create: item,
      // The quantity the service computed, not an increment: it already capped the total
      // against the stock, and letting the database add would lose that ceiling.
      update: { quantity: item.quantity, unitPriceCents: item.unitPriceCents },
    });
  }

  async setQuantity(cartId: string, variantId: string, quantity: number): Promise<boolean> {
    try {
      await this.client.cartItem.update({
        where: { cartId_variantId: { cartId, variantId } },
        data: { quantity },
      });

      return true;
    } catch (error) {
      if (errorCodeOf(error) === RECORD_NOT_FOUND) {
        return false;
      }
      throw error;
    }
  }

  async removeItem(cartId: string, variantId: string): Promise<boolean> {
    const result = await this.client.cartItem.deleteMany({ where: { cartId, variantId } });

    return result.count > 0;
  }

  async clear(cartId: string): Promise<void> {
    await this.client.cartItem.deleteMany({ where: { cartId } });
  }

  async setCurrency(cartId: string, currency: string): Promise<void> {
    await this.client.cart.update({ where: { id: cartId }, data: { currency } });
  }
}
